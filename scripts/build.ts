#!/usr/bin/env bun
// Generates every product's theme file from palette.json into dist/.
// Usage: bun run build        (writes dist/)
//        bun run build --check (fails if dist/ is out of date)

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const CHECK = process.argv.includes("--check")

type Palette = { name: string; colors: Record<string, string> }
const palette: Palette = JSON.parse(readFileSync(join(ROOT, "palette.json"), "utf8"))
const raw = palette.colors

// ---------- colour helpers ----------
const hex6 = (h: string) => h.slice(0, 7).toLowerCase()
const rgb = (h: string): [number, number, number] => {
  const s = hex6(h).slice(1)
  return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16)) as [number, number, number]
}
const toHex = (c: number[]) => "#" + c.map((x) => Math.round(x).toString(16).padStart(2, "0")).join("")
const mix = (a: string, b: string, t: number) => {
  const [x, y] = [rgb(a), rgb(b)]
  return toHex(x.map((v, i) => v * (1 - t) + y[i] * t))
}
// Herdr stores some colours as #rrggbbaa (white overlays). Flatten them over a base.
const flatten = (c: string, over: string) => {
  if (c.length !== 9) return hex6(c)
  return mix(over, c, parseInt(c.slice(7, 9), 16) / 255)
}

// ---------- resolved palette (everything opaque #rrggbb) ----------
const bg = hex6(raw.background)
const c = {
  bg,
  canvas: hex6(raw.canvas),
  chrome: hex6(raw.chrome),
  popover: hex6(raw.popover),
  raised: hex6(raw.raised),
  fg: hex6(raw.foreground),
  fgTerm: hex6(raw.terminal_foreground),
  muted: hex6(raw.muted),
  dim: hex6(raw.dim),
  selection: hex6(raw.selection),
  cursor: hex6(raw.cursor),
  accent: hex6(raw.accent),
  accentFg: hex6(raw.accent_foreground),
  border: flatten(raw.border, bg),
  hover: flatten(raw.hover, bg),
  selected: flatten(raw.selected, bg),
  input: flatten(raw.input, bg),
  working: hex6(raw.working),
  done: hex6(raw.done),
  blocked: hex6(raw.blocked),
  ansi: Array.from({ length: 16 }, (_, i) => hex6(raw[`ansi${i}`])),
}
const [black, red, green, yellow, blue, magenta, cyan, white] = c.ansi.slice(0, 8)
const [, bRed, bGreen, bYellow, bBlue, bMagenta, bCyan] = c.ansi.slice(8)
const gray = c.ansi[8]

const banner = (cm: string) =>
  `${cm} Generated by scripts/build.ts from palette.json. Do not edit by hand.`

const outputs = new Map<string, string>()

// ---------- Kitty ----------
{
  const lines = [
    "## name: Graphite",
    "## author: graphite-theme",
    "## license: Apache-2.0 (palette from Herdr)",
    "## upstream: https://github.com/herdrdev/herdr",
    "## blurb: Muted dark theme matching Herdr's graphite preset.",
    "",
    banner("#"),
    "",
    `foreground              ${c.fgTerm}`,
    `background              ${c.bg}`,
    `selection_foreground    ${c.fg}`,
    `selection_background    ${c.selection}`,
    `cursor                  ${c.cursor}`,
    `cursor_text_color       ${c.bg}`,
    `url_color               ${c.accent}`,
    "",
    `active_border_color     ${c.accent}`,
    `inactive_border_color   ${c.border}`,
    `bell_border_color       ${c.working}`,
    "",
    `active_tab_foreground   ${c.fg}`,
    `active_tab_background   ${c.bg}`,
    `inactive_tab_foreground ${c.muted}`,
    `inactive_tab_background ${c.chrome}`,
    `tab_bar_background      ${c.chrome}`,
    `tab_bar_margin_color    ${c.chrome}`,
    "",
    `mark1_foreground ${c.bg}`,
    `mark1_background ${c.accent}`,
    `mark2_foreground ${c.bg}`,
    `mark2_background ${magenta}`,
    `mark3_foreground ${c.bg}`,
    `mark3_background ${cyan}`,
    "",
    ...c.ansi.map((v, i) => `color${i}`.padEnd(24) + v),
    "",
  ]
  outputs.set("dist/kitty/graphite.conf", lines.join("\n"))
}

// ---------- tmux ----------
{
  // Powerline glyphs: arrows between status segments (U+E0B0 / U+E0B2), plus icons.
  const R = "", L = "", SEP = "", HOST = "", PANE = ""
  const lines = [
    banner("#"),
    "# Requires tmux >= 3.0 (variables) and a Powerline/Nerd Font for the glyphs.",
    "",
    `primary="${c.accent}"`,
    `bg="${c.chrome}"`,
    `bg_light="${c.raised}"`,
    `bg_select="${c.selection}"`,
    "",
    `text_color_primary="${c.accent}"`,
    `text_color_light="${c.fgTerm}"`,
    `text_color_dark="${c.bg}"`,
    "",
    `active_pane_border_color="${c.accent}"`,
    `inactive_pane_border_color="${c.selection}"`,
    `active_pane_bg="${c.bg}"`,
    `inactive_pane_bg="${c.canvas}"`,
    `inactive_pane_text_color="${c.muted}"`,
    "",
    "# Copy mode",
    `set -g mode-style "fg=\${text_color_light},bg=\${bg_select}"`,
    "",
    "# Messages",
    `set -g message-style "fg=\${text_color_primary},bg=\${bg_light},fill=\${bg_light}"`,
    `set -g message-command-style "fg=\${text_color_primary},bg=\${bg_light},fill=\${bg_light}"`,
    "",
    "# Panes",
    `set -g pane-border-style "fg=\${inactive_pane_border_color}"`,
    `set -g pane-active-border-style "fg=\${active_pane_border_color}"`,
    `set-window-option -g window-style "fg=\${inactive_pane_text_color},bg=\${inactive_pane_bg}"`,
    `set-window-option -g window-active-style "fg=\${text_color_light},bg=\${active_pane_bg}"`,
    "",
    "# Status bar",
    `set -g status "on"`,
    `set -g status-justify "left"`,
    `set -g status-style "fg=\${text_color_primary},bg=\${bg}"`,
    `set -g status-left-length "100"`,
    `set -g status-right-length "100"`,
    `set -g status-left-style NONE`,
    `set -g status-right-style NONE`,
    "",
    `set -g status-left "#[fg=\${text_color_dark},bg=\${primary},bold] ${HOST} #S #{?#{!=:#{window_panes},1}, ${SEP} ${PANE} #P,} #[fg=\${primary},bg=\${bg},nobold,nounderscore,noitalics]${R}"`,
    `set -g status-right "#[fg=\${bg_light},bg=\${bg},nobold,nounderscore,noitalics]${L}#[fg=\${text_color_primary},bg=\${bg_light}] %a %H:%M #[fg=\${primary},bg=\${bg_light},nobold,nounderscore,noitalics]${L}#[fg=\${text_color_dark},bg=\${primary},bold] %Y-%m-%d "`,
    "",
    `setw -g window-status-activity-style "underscore,fg=\${text_color_light},bg=\${bg}"`,
    `setw -g window-status-style "NONE,fg=\${text_color_light},bg=\${bg}"`,
    `setw -g window-status-separator ""`,
    `setw -g window-status-format "#[fg=\${bg},bg=\${bg},nobold,nounderscore,noitalics]${R}#[default] #I:#W "`,
    `setw -g window-status-current-format "#[fg=\${bg},bg=\${bg_light},nobold,nounderscore,noitalics]${R}#[fg=\${text_color_primary},bg=\${bg_light},bold] #I:#W #[fg=\${bg_light},bg=\${bg},nobold,nounderscore,noitalics]${R}"`,
    "",
  ]
  outputs.set("dist/tmux/graphite.conf", lines.join("\n"))
}

// ---------- Neovim palette (loaded by lua/graphite/palette.lua) ----------
{
  const entries: [string, string][] = [
    ["bg", c.bg], ["bg_canvas", c.canvas], ["bg_chrome", c.chrome], ["bg_popover", c.popover],
    ["bg_raised", c.raised], ["bg_hover", c.hover], ["bg_selected", c.selected],
    ["fg", c.fg], ["fg_term", c.fgTerm], ["muted", c.muted], ["dim", c.dim],
    ["selection", c.selection], ["cursor", c.cursor], ["accent", c.accent],
    ["accent_fg", c.accentFg], ["border", c.border], ["input", c.input],
    ["working", c.working], ["done", c.done], ["blocked", c.blocked],
    ["black", black], ["red", red], ["green", green], ["yellow", yellow], ["blue", blue],
    ["magenta", magenta], ["cyan", cyan], ["white", white],
    ["gray", gray], ["bright_red", bRed], ["bright_green", bGreen], ["bright_yellow", bYellow],
    ["bright_blue", bBlue], ["bright_magenta", bMagenta], ["bright_cyan", bCyan],
    ["bright_white", c.ansi[15]],
  ]
  const lua = [
    banner("--"),
    "return {",
    ...entries.map(([k, v]) => `  ${k} = "${v}",`),
    "  ansi = {",
    ...c.ansi.map((v) => `    "${v}",`),
    "  },",
    "}",
    "",
  ]
  outputs.set("dist/nvim/palette.lua", lua.join("\n"))
}

// ---------- opencode ----------
{
  const base = JSON.parse(readFileSync(join(ROOT, "opencode/base.json"), "utf8"))
  const b = base.base

  // Dark-mode hue ramps: 100 lightest .. 900 darkest, vivid colour at 400.
  const ramp = (v: string) => ({
    "100": mix(v, "#ffffff", 0.8), "200": mix(v, "#ffffff", 0.4), "300": mix(v, c.bg, 0.3),
    "400": v, "500": mix(v, c.bg, 0.5), "600": mix(v, c.bg, 0.75),
    "700": mix(v, c.bg, 0.86), "800": mix(v, c.bg, 0.93), "900": mix(v, c.bg, 0.97),
  })
  const hue: Record<string, unknown> = {
    red: ramp(red), orange: ramp(yellow), green: ramp(green),
    cyan: ramp(cyan), blue: ramp(blue), purple: ramp(magenta),
    gray: {
      "100": c.fg, "200": c.fgTerm, "300": c.muted, "400": c.dim,
      "500": c.raised, "600": c.popover,
      "700": mix(c.bg, c.popover, 0.5), "800": mix(c.bg, c.popover, 0.25), "900": c.bg,
    },
    accent: "$hue.blue", interactive: "$hue.blue", neutral: "$hue.gray",
  }

  b.categorical = ["blue", "purple", "green", "orange", "red"]
  b.border.base = c.border
  b.scrollbar.base = c.dim
  b.text.feedback.warning.base = c.working
  // Highlighted text (e.g. the [Image 1] pill, focused rows) is dark on a bright fill.
  b.text.action.primary.$focused = "$hue.neutral.900"
  b.background.action.primary.$focused = "$hue.interactive.400"
  b.diff = {
    text: { added: green, removed: red, context: c.muted, hunkHeader: c.muted },
    background: {
      added: mix(c.bg, green, 0.1), removed: mix(c.bg, red, 0.1), context: "$hue.neutral.700",
    },
    highlight: { added: green, removed: red },
    lineNumber: {
      text: c.dim,
      background: { added: mix(c.bg, green, 0.07), removed: mix(c.bg, red, 0.07) },
    },
  }
  b.syntax = {
    comment: c.dim, keyword: magenta, function: blue, variable: red, string: green,
    number: yellow, type: c.working, operator: cyan, punctuation: c.fgTerm,
  }
  b.markdown = {
    text: c.fgTerm, heading: magenta, link: blue, linkText: cyan, code: green,
    blockQuote: c.dim, emphasis: c.working, strong: yellow, horizontalRule: c.dim,
    listItem: blue, listEnumeration: cyan, image: blue, imageText: cyan, codeBlock: c.fgTerm,
  }

  const theme = { $schema: base.$schema, base: b, dark: { hue } }
  outputs.set("dist/opencode/graphite.json", JSON.stringify(theme, null, 2) + "\n")
}

// ---------- write / check ----------
let stale = 0
for (const [rel, content] of outputs) {
  const file = join(ROOT, rel)
  if (CHECK) {
    if (!existsSync(file) || readFileSync(file, "utf8") !== content) {
      console.error(`stale: ${rel}`)
      stale++
    }
    continue
  }
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
  console.log(`wrote ${rel}`)
}
if (CHECK) {
  if (stale) process.exit(1)
  console.log("dist/ is up to date")
}
